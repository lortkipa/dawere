// "a **b** c" → text nodes, the middle one bold.
function inline(text: string): JSONContent[] {
  return text
    .split(/(\*\*[^*]+\*\*)/)
    .filter(Boolean)
    .map((part) =>
      part.startsWith("**") && part.endsWith("**")
        ? { type: "text", text: part.slice(2, -2), marks: [{ type: "bold" }] }
        : { type: "text", text: part },
    );
}

function toDoc(text: string): JSONContent {
  const content = text
    .trim()
    .split(/\n\s*\n/)
    .map((block): JSONContent => {
      const lines = block.trim().split("\n");
      if (lines[0].startsWith("## ")) {
        return { type: "heading", attrs: { level: 2 }, content: inline(lines[0].slice(3)) };
      }
      if (lines.every((line) => line.startsWith("- "))) {
        return {
          type: "bulletList",
          content: lines.map((line) => ({
            type: "listItem",
            content: [{ type: "paragraph", content: inline(line.slice(2)) }],
          })),
        };
      }
      return { type: "paragraph", content: inline(lines.join(" ")) };
    });
  return { type: "doc", content };
}

export function defaultLegal(doc: LegalDoc) {
  const { title, text } = sources[doc];
  return { title, body: toDoc(text) };
}
